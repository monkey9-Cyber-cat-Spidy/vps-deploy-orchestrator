function generateNginxConfig({ domain, upstreamPort = 3000, enableWebSockets = true, enableSsl = true }) {
  const upstreamName = `app_${domain.replace(/[^a-zA-Z0-9]/g, '_')}`;

  const wsHeaders = enableWebSockets ? `
        proxy_set_header Upgrade \$http_upgrade;
        proxy_set_header Connection "upgrade";` : '';

  const sslBlock = enableSsl ? `
server {
    listen 80;
    server_name ${domain} www.${domain};
    return 301 https://\$host\$request_uri;
}

server {
    listen 443 ssl http2;
    server_name ${domain} www.${domain};

    ssl_certificate /etc/letsencrypt/live/${domain}/fullchain.pem;
    ssl_certificate_key /etc/letsencrypt/live/${domain}/privkey.pem;
    ssl_protocols TLSv1.2 TLSv1.3;
    ssl_ciphers HIGH:!aNULL:!MD5;
    ssl_session_cache shared:SSL:10m;
    ssl_session_timeout 10m;

    # Security Headers
    add_header X-Frame-Options "SAMEORIGIN" always;
    add_header X-XSS-Protection "1; mode=block" always;
    add_header X-Content-Type-Options "nosniff" always;
    add_header Referrer-Policy "strict-origin-when-cross-origin" always;
    add_header Strict-Transport-Security "max-age=31536000; includeSubDomains" always;

    # Compression
    gzip on;
    gzip_vary on;
    gzip_min_length 1024;
    gzip_proxied any;
    gzip_types text/plain text/css application/json application/javascript text/xml application/xml;

    location / {
        proxy_pass http://${upstreamName};
        proxy_http_version 1.1;${wsHeaders}
        proxy_set_header Host \$host;
        proxy_set_header X-Real-IP \$remote_addr;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto \$scheme;
        proxy_read_timeout 60s;
        proxy_connect_timeout 60s;
    }
}` : `
server {
    listen 80;
    server_name ${domain} www.${domain};

    location / {
        proxy_pass http://${upstreamName};
        proxy_http_version 1.1;${wsHeaders}
        proxy_set_header Host \$host;
        proxy_set_header X-Real-IP \$remote_addr;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto \$scheme;
    }
}`;

  return `# Nginx Reverse Proxy Configuration for ${domain}
# Generated by vps-deploy-orchestrator

upstream ${upstreamName} {
    server 127.0.0.1:${upstreamPort} max_fails=3 fail_timeout=10s;
    keepalive 32;
}
${sslBlock}
`;
}

module.exports = { generateNginxConfig };
